//! 錬金で出る護石の中身を、乱数から決める (マカフシギ錬金で出る 2 種類の護石の表と、mhxx-rng の getcharm)。
//!
//! apmnnn/mhxx-rng (https://github.com/apmnnn/mhxx-rng) のノートブック (mhxx-rng.ipynb) からの移植。表はノートブックの
//! set_blue / set_red の値をそのまま書き写したもの。ライセンスは [`super::xorshift`] の記載を参照 (apmnnn/mhxx-rng, MIT)。

use crate::types::SkillId;

/// 護石の種類ごとの表
pub struct Table {
    /// 第 1 スキルと、そのポイントの (最小, 最大)
    pub skill1: &'static [SkillId],
    pub pts1: &'static [(u8, u8)],
    /// 第 2 スキルと、ポイントの (マイナスのときの幅, 最大)。錬金では最大だけを使う (マイナスは出ない)
    pub skill2: &'static [SkillId],
    pub pts2: &'static [(u8, u8)],
    /// 「充填度」(1〜20) ごとの、スロットが 1・2・3 個になる乱数 (0〜99) の下限
    pub slots: [(u8, u8, u8); 20],
    /// 乱数 (0〜99) がこれ未満なら第 2 スキルなし
    pub no_skill2: u32,
}

/// 乱数から決まった護石の中身
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Generated {
    pub skill1: SkillId,
    pub pts1: i8,
    /// 第 2 スキル。第 1 スキルと同じスキルになったときも、ここには入る (鑑定画面では第 2 スキルなしに見える)
    pub skill2: Option<SkillId>,
    pub pts2: i8,
    pub slots: u8,
}

impl Generated {
    /// 鑑定画面に第 2 スキルが出るか (第 1 スキルと同じスキルなら出ない)
    pub fn shows_skill2(&self) -> bool {
        self.skill2.is_some_and(|s| s != self.skill1) && self.pts2 > 0
    }
}

impl Table {
    /// 7 個の乱数 r から錬金で出る護石を作る (mhxx-rng の getcharm、_origin = 0)
    pub fn make(&self, r: &[u32; 7]) -> Generated {
        let id1 = r[0] as usize % self.skill1.len();
        let id2 = r[3] as usize % self.skill2.len();
        let (lo1, s1) = self.pts1[id1];
        let s2 = self.pts2[id2].1;
        let tmp1 = r[1] % (s1 - lo1 + 1) as u32 + lo1 as u32;
        let (skill2, pts2, tmp2, q5) = if r[2] % 100 >= self.no_skill2 {
            let p = r[4] % s2 as u32 + 1;
            // 第 1 スキルと同じスキルなら、充填度には数えない
            let tmp2 = if self.skill1[id1] == self.skill2[id2] {
                0
            } else {
                p
            };
            (Some(self.skill2[id2]), p as i8, tmp2, r[5])
        } else {
            (None, 0, 0, r[3])
        };
        let (s1, s2) = (s1 as u32, s2 as u32);
        let fill = (tmp1 * s2 + tmp2 * s1) * 10 / (s1 * s2);
        let v = (q5 % 100) as u8;
        let (a, b, c) = self.slots[fill as usize - 1];
        let slots = if v >= c {
            3
        } else if v >= b {
            2
        } else if v >= a {
            1
        } else {
            0
        };
        Generated {
            skill1: self.skill1[id1],
            pts1: tmp1 as i8,
            skill2,
            pts2,
            slots,
        }
    }

    /// この護石を作ったあと、次の護石の乱数までの間隔 (第 2 スキルが無ければ 4、あれば 6)
    pub fn stride(&self, r2: u32) -> usize {
        if r2 % 100 < self.no_skill2 { 4 } else { 6 }
    }
}

